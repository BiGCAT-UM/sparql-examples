#!/usr/bin/env python3
"""Generate SIB-style SPARQL example files from the WikiPathways SNORQL queries.

The WikiPathways SNORQL UI loads its example queries from the .rq files in
https://github.com/wikipathways/SPARQLQueries. Each file starts with a comment
header (title, category, description, optional keywords and params). This
script turns every .rq file listed in sources.tsv into one Turtle file in
examples/WikiPathways/, in the format of https://github.com/sib-swiss/sparql-examples.

sources.tsv fixes the number (and so the IRI) of every query and records where
each query comes from. Numbers are never reused or renumbered. The kinds are:

  rq      generated by this script from the .rq file in `source`
  manual  written by hand in this repository (never touched by this script)
  web     written by hand from a query on the WikiPathways website
  same    `source` is the same query as example `id`; no file of its own
  skip    `source` is not published here; `note` says why (id is "-")

Usage, from the repository root:

    python scripts/wikipathways/rq2ttl.py --source ../SPARQLQueries
    python scripts/wikipathways/rq2ttl.py --source ../SPARQLQueries --check

New .rq files in the source checkout are appended to sources.tsv with the next
free number. --check writes nothing and exits with 1 if any file would change.

Each generated example links (dcterms:source) to the .rq file at the commit that
last changed it, and records that commit's date as dcterms:modified, so the link
keeps showing the version the example was made from. The source checkout must
therefore be clean for the .rq files and those commits must be on the upstream
master branch (as last fetched); --allow-unmerged skips the second check, for
trying out a branch before its pull request is merged.
"""

import argparse
import csv
import pathlib
import re
import subprocess
import sys
import urllib.parse

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import RDFS

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
OUT_DIR = REPO / "examples" / "WikiPathways"
SOURCES_TSV = HERE / "sources.tsv"
PREFIXES_TTL = OUT_DIR / "prefixes.ttl"

EX_BASE = "https://bigcat-um.github.io/sparql-examples/WikiPathways/"
TARGET = "https://sparql.wikipathways.org/sparql"
SOURCE_BASE = "https://github.com/wikipathways/SPARQLQueries/blob/"
UPSTREAM_BRANCH = "origin/master"
LICENSE = "https://www.gnu.org/licenses/gpl-3.0.html"

SH = Namespace("http://www.w3.org/ns/shacl#")
SCHEMA = Namespace("https://schema.org/")
SPEX = Namespace("https://purl.expasy.org/sparql-examples/ontology#")

FIELDS = ("id", "kind", "source", "note")
EXCLUDED_DIRS = {".git", ".github", ".planning", "scripts", "tests"}

# Extra keywords per source folder, on top of the category.
FOLDER_KEYWORDS = {
    "A. Metadata/datacounts": ["counts"],
    "A. Metadata/species": ["organism"],
    "B. Communities/Inborn Errors of Metabolism": ["inborn errors of metabolism", "metabolism"],
    "B. Communities/Lipids": ["lipids", "LIPID MAPS"],
    "B. Communities/Reactome": ["Reactome"],
    "C. Collaborations/AOP-Wiki": ["AOP-Wiki", "metabolite"],
    "C. Collaborations/MetaNetX": ["MetaNetX", "reaction"],
    "C. Collaborations/MolMeDB": ["MolMeDB", "PubChem"],
    "C. Collaborations/neXtProt": ["neXtProt", "protein"],
    "C. Collaborations/smallMolecules_Rhea_IDSM": ["Rhea", "IDSM", "reaction"],
    "I. DirectedSmallMoleculesNetwork (DSMN)": ["directed small molecules network"],
}

QUERY_FORMS = {
    "SELECT": ("SPARQLSelectExecutable", "select", SH),
    "ASK": ("SPARQLAskExecutable", "ask", SH),
    "CONSTRUCT": ("SPARQLConstructExecutable", "construct", SH),
    "DESCRIBE": ("SPARQLDescribeExecutable", "describe", SPEX),
}

HEADER_FIELD = re.compile(r"^#\s*(title|category|description|keywords|param):\s?(.*)$")


class RqQuery:
    """One .rq file from the SPARQLQueries repository."""

    def __init__(self, path, rel):
        self.path = path
        self.rel = rel
        self.title = ""
        self.category = ""
        self.description = []
        self.keywords = []
        self.params = []  # (name, type, default, label)
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        lines = text.split("\n")
        n = 0
        field = None
        while n < len(lines) and lines[n].startswith("#"):
            m = HEADER_FIELD.match(lines[n])
            if m:
                field, value = m.group(1), m.group(2).strip()
                if field == "title":
                    self.title = value
                elif field == "category":
                    self.category = value
                elif field == "description":
                    self.description.append(value)
                elif field == "keywords":
                    self.keywords += [k.strip() for k in value.split(",") if k.strip()]
                elif field == "param":
                    parts = [p.strip() for p in value.split("|")]
                    parts += [""] * (4 - len(parts))
                    self.params.append(tuple(parts[:4]))
            elif field == "description":
                # Continuation line ("#   more text") of a multi-line description.
                self.description.append(lines[n].lstrip("#").strip())
            n += 1
        self.body = "\n".join(lines[n:]).strip("\n")

    @property
    def comment(self):
        text = " ".join(d for d in self.description if d)
        if self.params:
            values = ", ".join(f'{label or name} "{default}"' for name, _, default, label in self.params)
            text += (f" This example uses the default value{'s' if len(self.params) > 1 else ''}"
                     f" ({values}); the WikiPathways SNORQL UI lets you change "
                     f"{'them' if len(self.params) > 1 else 'it'}.")
        return text

    def query(self, namespaces):
        """Runnable query: parameters filled in and missing PREFIX lines added."""
        defaults = {name: default for name, _, default, _ in self.params}

        def fill(m):
            if m.group(1) not in defaults:
                raise ValueError(f"{self.rel}: no default for parameter {{{{{m.group(1)}}}}}")
            return defaults[m.group(1)]

        body = re.sub(r"\{\{\s*(\w+)\s*\}\}", fill, self.body)
        missing = sorted(used_prefixes(body) - declared_prefixes(body))
        unknown = [p for p in missing if p not in namespaces]
        if unknown:
            raise ValueError(f"{self.rel}: prefixes not in prefixes.ttl: {', '.join(unknown)}")
        prologue = "".join(f"PREFIX {p}: <{namespaces[p]}>\n" for p in missing)
        if prologue and not re.match(r"(?i)\s*PREFIX\b", body):
            prologue += "\n"  # blank line between the prologue and the query
        return (prologue + body).strip() + "\n"


def strip_strings_iris_comments(query, keep_iris=False):
    """Blank out IRIs, string literals and comments so prefixed names can be found.

    With keep_iris=True only comments and string literals are removed.
    """
    out = []
    i, n = 0, len(query)
    while i < n:
        c = query[i]
        if c == "#":
            j = query.find("\n", i)
            i = n if j < 0 else j
        elif c == "<":
            j = query.find(">", i)
            # A '<' that is a comparison operator has whitespace or '=' after it.
            if j > 0 and not re.search(r"[\s]", query[i:j]):
                out.append(query[i:j + 1] if keep_iris else " ")
                i = j + 1
            else:
                out.append(c)
                i += 1
        elif c in "\"'":
            quote = query[i:i + 3] if query[i:i + 3] in ('"""', "'''") else c
            j = i + len(quote)
            while j < n and query[j:j + len(quote)] != quote:
                j += 2 if query[j] == "\\" else 1
            out.append(" ")
            i = j + len(quote)
        else:
            out.append(c)
            i += 1
    return "".join(out)


def used_prefixes(query):
    code = strip_strings_iris_comments(query)
    code = re.sub(r"(?im)^\s*PREFIX\s+[\w.-]*:\s*", " ", code)
    # Prefixed names; skip variables (?x, $x) and the fragments of full IRIs.
    names = re.findall(r"(?<![\w?$.:-])([A-Za-z][\w.-]*)?:(?=[\w%(\\]|\s|[;,.)\]}]|$)", code)
    return {n for n in names}


def declared_prefixes(query):
    code = strip_strings_iris_comments(query)
    return set(re.findall(r"(?im)\bPREFIX\s+([\w.-]*)\s*:", code))


def query_form(query):
    code = strip_strings_iris_comments(query)
    code = re.sub(r"(?im)^\s*(PREFIX\s+[\w.-]*:|BASE)\s*", " ", code)
    m = re.search(r"(?i)\b(SELECT|ASK|CONSTRUCT|DESCRIBE)\b", code)
    if not m:
        raise ValueError("cannot find the query form")
    return m.group(1).upper()


def services(query):
    code = strip_strings_iris_comments(query, keep_iris=True)
    return sorted(set(re.findall(r"(?i)\bSERVICE\s+(?:SILENT\s+)?<([^>]+)>", code)))


def load_namespaces():
    g = Graph()
    g.parse(PREFIXES_TTL, format="turtle")
    return {str(p): str(ns) for _, d in g.subject_objects(SH.declare)
            for p in g.objects(d, SH.prefix) for ns in g.objects(d, SH.namespace)}


def turtle_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def turtle_long_string(text):
    text = text.replace("\\", "\\\\")
    # Escape quotes that would end the long string early or merge with the closing quotes.
    text = re.sub(r'"(?=""|"*$)', r'\\"', text)
    return '"""' + text + '"""'


def keywords_for(rq):
    words = [rq.category.lower() if rq.category not in ("DSMN",) else rq.category]
    folder = str(pathlib.PurePosixPath(rq.rel).parent)
    words += FOLDER_KEYWORDS.get(folder, [])
    words += rq.keywords
    seen, result = set(), []
    for w in words:
        if w and w.lower() not in seen:
            seen.add(w.lower())
            result.append(w)
    return result


def git(source, *args):
    return subprocess.run(["git", "-C", str(source), *args], capture_output=True, text=True)


def source_version(source, rel, allow_unmerged):
    """Commit (hash, date) that last changed `rel` in the source checkout."""
    if git(source, "status", "--porcelain", "--", rel).stdout.strip():
        raise ValueError(f"{rel} has uncommitted changes in {source}")
    out = git(source, "log", "-1", "--format=%H %cs", "--", rel).stdout.split()
    if len(out) != 2:
        raise ValueError(f"{rel} has no git history in {source}")
    sha, date = out
    if not allow_unmerged and git(source, "merge-base", "--is-ancestor", sha, UPSTREAM_BRANCH).returncode != 0:
        raise ValueError(f"{rel}: commit {sha[:7]} is not on {UPSTREAM_BRANCH}; merge it upstream "
                         "(and fetch) first, or pass --allow-unmerged to try it out")
    return sha, date


def render(ex_id, rq, namespaces, version):
    query = rq.query(namespaces).rstrip("\n")
    form = query_form(query)
    cls, prop, _ = QUERY_FORMS[form]
    prop_curie = f"spex:{prop}" if form == "DESCRIBE" else f"sh:{prop}"
    lines = [
        "@prefix dcterms: <http://purl.org/dc/terms/> .",
        f"@prefix ex: <{EX_BASE}> .",
        "@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix schema: <https://schema.org/> .",
        "@prefix sh: <http://www.w3.org/ns/shacl#> .",
        "@prefix spex: <https://purl.expasy.org/sparql-examples/ontology#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        f"ex:{ex_id} a sh:SPARQLExecutable,",
        f"       {'spex' if form == 'DESCRIBE' else 'sh'}:{cls} ;",
        f"    rdfs:label {turtle_string(rq.title)}@en ;",
        f"    rdfs:comment {turtle_string(rq.comment)}@en ;",
        "    sh:prefixes _:sparql_examples_prefixes ;",
        f"    {prop_curie} {turtle_long_string(query)} ;",
        f"    schema:target <{TARGET}> ;",
        "    schema:keywords " + ", ".join(turtle_string(k) for k in keywords_for(rq)) + " ;",
    ]
    for service in services(query):
        lines.append(f"    spex:federatesWith <{service}> ;")
    sha, date = version
    lines.append(f"    dcterms:source <{SOURCE_BASE}{sha}/{urllib.parse.quote(rq.rel)}> ;")
    lines.append(f'    dcterms:modified "{date}"^^xsd:date ;')
    lines.append(f"    dcterms:license <{LICENSE}> .")
    ttl = "\n".join(lines) + "\n"
    check_round_trip(ex_id, ttl, query, prop, form)
    return ttl


def check_round_trip(ex_id, ttl, query, prop, form):
    g = Graph()
    g.parse(data=ttl, format="turtle")
    subject = URIRef(EX_BASE + ex_id)
    ns = SPEX if form == "DESCRIBE" else SH
    found = [str(o) for o in g.objects(subject, ns[prop])]
    if found != [query]:
        raise ValueError(f"{ex_id}: query text does not survive the Turtle round trip")
    if not any(isinstance(o, Literal) for o in g.objects(subject, RDFS.comment)):
        raise ValueError(f"{ex_id}: no rdfs:comment")


def read_sources():
    with open(SOURCES_TSV, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def write_sources(rows):
    with open(SOURCES_TSV, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, delimiter="\t", lineterminator="\n")
        w.writeheader()
        for row in rows:
            w.writerow({k: row.get(k, "") for k in FIELDS})


def source_files(source):
    files = []
    for p in source.rglob("*.rq"):
        rel = p.relative_to(source)
        if rel.parts[0] in EXCLUDED_DIRS:
            continue
        files.append(rel.as_posix())
    return sorted(files, key=str.casefold)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True, type=pathlib.Path,
                    help="checkout of https://github.com/wikipathways/SPARQLQueries")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if any file would change")
    ap.add_argument("--allow-unmerged", action="store_true",
                    help=f"accept source commits that are not on {UPSTREAM_BRANCH} yet")
    args = ap.parse_args()

    source = args.source.resolve()
    rows = read_sources()
    known = {r["source"] for r in rows}
    next_id = max(int(r["id"]) for r in rows if r["id"].isdigit()) + 1
    changed = []

    new_rows = []
    for rel in source_files(source):
        if rel not in known:
            new_rows.append({"id": f"{next_id:03d}", "kind": "rq", "source": rel, "note": ""})
            next_id += 1
    if new_rows:
        rows += new_rows
        changed.append(SOURCES_TSV)
        for r in new_rows:
            print(f"new source {r['source']} -> {r['id']}")

    namespaces = load_namespaces()
    outputs = {}
    for row in rows:
        if not row["source"].endswith(".rq"):
            continue
        path = source / row["source"]
        if not path.exists():
            print(f"WARNING: {row['id']} source is gone: {row['source']}", file=sys.stderr)
            continue
        if row["kind"] != "rq":
            continue
        version = source_version(source, row["source"], args.allow_unmerged)
        outputs[OUT_DIR / f"{row['id']}.ttl"] = render(row["id"], RqQuery(path, row["source"]), namespaces, version)

    for path, ttl in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != ttl:
            changed.append(path)
            if not args.check:
                path.write_text(ttl, encoding="utf-8")
    if new_rows and not args.check:
        write_sources(rows)

    generated = sum(1 for r in rows if r["kind"] == "rq")
    same = sum(1 for r in rows if r["kind"] == "same" and r["source"].endswith(".rq"))
    skipped = sum(1 for r in rows if r["kind"] == "skip" and r["source"].endswith(".rq"))
    print(f"{len(source_files(source))} .rq files in the source: {generated} generated, "
          f"{same} same as another example, {skipped} skipped")
    for path in changed:
        print(("would change " if args.check else "updated ") + str(path.relative_to(REPO)))
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
